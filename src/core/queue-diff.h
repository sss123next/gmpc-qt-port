#pragma once

/**
 * @file queue-diff.h
 * @brief Инкрементальное обновление очереди по `plchanges` — чистая часть.
 *
 * Замеры на одноразовом MPD 0.25 (очередь из шести треков, сокет в /tmp):
 *  - `plchangesposid`/`plchanges` сообщают только те трэки, у которых изменилась
 *    позиция **или** теги: правка тегов у второго трэка очереди из пяти даёт ровно
 *    одну запись (`cpos: 1 Id: 14`) — соседние строки в ответе не появляются;
 *  - удалённый трэк в диффе НЕ упоминается: после `deleteid 3` из шести строк
 *    приходят только сдвинувшиеся id 4,5,6 со своими новыми позициями;
 *  - после `clear` оба запроса отдают пустой ответ при `playlistlength: 0`;
 *  - нулевая версия и версия «из будущего» ACK не дают — сервер возвращает всю
 *    очередь, так что расхождение само превращается в полный список позиций.
 *
 * Отсюда алгоритм слияния: записи диффа занимают свои новые позиции, остальные
 * строки заполняют освободившиеся слоты в прежнем порядке, а непоместившиеся — это
 * и есть удалённые трэки (удалённый трэк всегда стоит ниже всех стабильных: стоял
 * бы выше — сдвинул бы их, и они попали бы в дифф). Результат сверяется с
 * `playlistlength` из `status`: не сошлось — нужен полный `listqueue`.
 */

#include <QList>

#include "core/playlist-model.h"

/// Что получилось после применения диффа к локальной копии.
struct QueueApplyResult {
    /// Дифф применён; false — копия больше не доверяется ответу сервера.
    bool ok = false;

    enum class Kind {
        None,       ///< изменений нет
        TagsOnly,   ///< состав и порядок очереди прежние, обновились только теги
        Structural, ///< очередь перестроилась: добавления, удаления, перемещения
    } kind = Kind::Structural;

    /// Номера строк с обновлёнными тегами (смысл только для TagsOnly).
    QList<int> tagRows;
};

/** @brief Применяет к локальной копии очереди ответ `plchanges <version>`.
 *  @param queue     локальная копия; при true становится новым состоянием очереди
 *  @param changes   трэки из ответа: у каждого заполнены id и **новая** позиция
 *  @param newLength `playlistlength` из status, полученного вместе с этим диффом
 *
 *  Отказ (`ok == false`) — штатный результат, а не ошибка: он означает, что дифф
 *  не описывает очередь целиком (например события idle терялись дольше, чем сервер
 *  хранит историю изменений), и вызывающий должен перечитать очередь полностью.
 */
[[nodiscard]] QueueApplyResult applyQueueChanges(QList<SongEntry> &queue,
                                                 const QList<SongEntry> &changes,
                                                 int newLength);
